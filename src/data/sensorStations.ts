// Generate dynamic evacuation waypoints from user location to shelter avoiding hazard points
export function generateEvacuationCorridor(
  startLat: number,
  startLng: number,
  targetLat: number,
  targetLng: number,
  hazards: { lat: number; lng: number; radiusKm: number }[]
): { waypoints: [number, number][]; steps: EvacuationNavigationStep[]; safeCorridorScore: number } {
  // Intermediate waypoints
  const steps: EvacuationNavigationStep[] = [];
  const waypoints: [number, number][] = [[startLat, startLng]];

  // 3 segments
  const mid1Lat = startLat + (targetLat - startLat) * 0.33;
  const mid1Lng = startLng + (targetLng - startLng) * 0.33;
  const mid2Lat = startLat + (targetLat - startLat) * 0.66;
  const mid2Lng = startLng + (targetLng - startLng) * 0.66;

  // Apply subtle detour curve away from hazards
  let offsetLat1 = 0;
  let offsetLng1 = 0;
  let offsetLat2 = 0;
  let offsetLng2 = 0;

  hazards.forEach((h) => {
    const distToMid1 = calculateGeoDistanceKm(mid1Lat, mid1Lng, h.lat, h.lng);
    if (distToMid1 < 2.0) {
      offsetLat1 += (mid1Lat - h.lat) * 0.4;
      offsetLng1 += (mid1Lng - h.lng) * 0.4;
    }
  });

  const wp1: [number, number] = [mid1Lat + offsetLat1, mid1Lng + offsetLng1];
  const wp2: [number, number] = [mid2Lat + offsetLat2, mid2Lng + offsetLng2];
  const wpTarget: [number, number] = [targetLat, targetLng];

  waypoints.push(wp1);
  waypoints.push(wp2);
  waypoints.push(wpTarget);

  const totalDist = calculateGeoDistanceKm(startLat, startLng, targetLat, targetLng);
  const stepDist = Math.round((totalDist * 1000) / 3);

  steps.push({
    stepNumber: 1,
    instruction: "Exit current building or area immediately with N95/mask on. Head towards the designated Green Air Corridor.",
    distanceMeters: stepDist,
    durationMinutes: Math.max(3, Math.round((stepDist / 4500) * 60)),
    airQualityStatus: "Low Exposure",
    waypoint: wp1,
  });

  steps.push({
    stepNumber: 2,
    instruction: "Follow low-smoke bypass corridor away from active toxic plumes. Maintain steady pace along shielded roadway.",
    distanceMeters: stepDist,
    durationMinutes: Math.max(4, Math.round((stepDist / 4500) * 60)),
    airQualityStatus: "Clean Air Corridor",
    waypoint: wp2,
  });

  steps.push({
    stepNumber: 3,
    instruction: "Arrive at Clean Air Evacuation Shelter entrance. Enter through positive-pressure airlock for medical triage & clean air.",
    distanceMeters: stepDist,
    durationMinutes: Math.max(3, Math.round((stepDist / 4500) * 60)),
    airQualityStatus: "Clean Air Corridor",
    waypoint: wpTarget,
  });

  return {
    waypoints,
    steps,
    safeCorridorScore: 94,
  };
}

